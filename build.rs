use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
};

const COMMANDS: &[&str] = &["check", "download", "install", "download_and_install"];

fn main() {
    // The published package has its own identity. Keep the runtime/ACL identity `updater`
    // so existing capabilities and the official JS client address the same plugin.
    // These are the desktop steps of tauri_plugin::Builder with an explicit plugin name.
    let name = "tauri-plugin-updater";
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo OUT_DIR"));
    let autogenerated = Path::new("permissions/autogenerated");
    std::fs::create_dir_all(autogenerated).expect("create permissions directory");
    tauri_utils::acl::build::autogenerate_command_permissions(
        &autogenerated.join("commands"),
        COMMANDS,
        "",
        true,
    );
    println!("cargo:rerun-if-changed=permissions");
    let permissions =
        tauri_utils::acl::build::define_permissions("./permissions/**/*.*", name, &out_dir, |_| {
            true
        })
        .expect("define updater permissions");
    tauri_utils::acl::schema::generate_permissions_schema(&permissions, "./permissions")
        .expect("generate permission schema");
    tauri_utils::acl::build::generate_docs(&permissions, autogenerated, "updater")
        .expect("generate permission reference");
    tauri_utils::acl::build::generate_allowed_commands(
        &out_dir,
        None,
        BTreeMap::from([(name.into(), permissions)]),
    )
    .expect("generate allowed updater commands");
    tauri_utils::plugin::define_global_api_script_path(Path::new("./api-iife.js"));

    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap();
    let mobile = target_os == "ios" || target_os == "android";
    alias("desktop", !mobile);
    alias("mobile", mobile);
}

// creates a cfg alias if `has_feature` is true.
// `alias` must be a snake case string.
fn alias(alias: &str, has_feature: bool) {
    println!("cargo:rustc-check-cfg=cfg({alias})");
    if has_feature {
        println!("cargo:rustc-cfg={alias}");
    }
}
